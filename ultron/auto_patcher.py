"""
auto_patcher.py - Automated Code Patching, Syntax Verification & Git Integration
Takes remediation blueprints generated by Ultron, applies contextual AST-verified
code modifications directly to source files, and creates isolated Git branches.
"""

import os
import ast
import subprocess
import logging
from typing import Dict, Any, List, Optional, Tuple
from .database import log_event

logger = logging.getLogger("sentinel.auto_patcher")

class AutoPatcher:
    """
    Applies source code patches, validates Python syntax, and prepares Git branches.
    """

    def verify_syntax(self, file_content: str, filename: str = "patch_test.py") -> Tuple[bool, Optional[str]]:
        """Verifies Python code syntax using the AST parser."""
        if not filename.endswith(".py"):
            return True, None
        try:
            ast.parse(file_content, filename=filename)
            return True, None
        except SyntaxError as e:
            return False, f"Erreur de syntaxe ligne {e.lineno}: {e.msg}"

    def apply_patch_to_file(self, file_path: str, search_block: str, replacement_block: str) -> Dict[str, Any]:
        """Safely applies a targeted code patch to a specific file with backup and AST validation."""
        if not os.path.isfile(file_path):
            return {"success": False, "error": f"Fichier introuvable : {file_path}"}

        try:
            with open(file_path, "r", encoding="utf-8") as f:
                original_content = f.read()

            if search_block not in original_content:
                return {
                    "success": False,
                    "error": "Le bloc cible n'a pas été trouvé textuellement dans le fichier source."
                }

            patched_content = original_content.replace(search_block, replacement_block, 1)

            # Validate syntax before writing
            valid, err = self.verify_syntax(patched_content, os.path.basename(file_path))
            if not valid:
                return {
                    "success": False,
                    "error": f"Validation AST échouée, patch rejeté pour éviter toute corruption : {err}"
                }

            # Write backup
            backup_path = f"{file_path}.bak_sentinel"
            with open(backup_path, "w", encoding="utf-8") as f:
                f.write(original_content)

            with open(file_path, "w", encoding="utf-8") as f:
                f.write(patched_content)

            log_event("AUTO_PATCH_APPLIED", "INFO", "AUTO_PATCHER",
                      f"Patch appliqué avec succès sur '{os.path.basename(file_path)}' (Backup: {os.path.basename(backup_path)})")

            return {
                "success": True,
                "file_path": file_path,
                "backup_path": backup_path,
                "message": "Patch appliqué et validé par l'analyseur de syntaxe AST."
            }
        except Exception as e:
            return {"success": False, "error": str(e)}

    def rollback_patch(self, file_path: str) -> Dict[str, Any]:
        """Restores file from .bak_sentinel backup."""
        backup_path = f"{file_path}.bak_sentinel"
        if not os.path.isfile(backup_path):
            return {"success": False, "error": "Aucun fichier de sauvegarde trouvé."}

        try:
            with open(backup_path, "r", encoding="utf-8") as f:
                content = f.read()
            with open(file_path, "w", encoding="utf-8") as f:
                f.write(content)
            os.remove(backup_path)
            return {"success": True, "message": "Fichier restauré à son état initial."}
        except Exception as e:
            return {"success": False, "error": str(e)}

    def create_git_patch_branch(self, project_dir: str, branch_name: str, commit_message: str) -> Dict[str, Any]:
        """Creates a dedicated Git branch and commits the patched files."""
        try:
            # Check if git repo
            if not os.path.isdir(os.path.join(project_dir, ".git")):
                return {"success": False, "error": "Le répertoire spécifié n'est pas un dépôt Git valide."}

            subprocess.run(["git", "checkout", "-b", branch_name], cwd=project_dir, capture_output=True, text=True, check=True)
            subprocess.run(["git", "add", "."], cwd=project_dir, capture_output=True, text=True, check=True)
            subprocess.run(["git", "commit", "-m", commit_message], cwd=project_dir, capture_output=True, text=True, check=True)

            return {
                "success": True,
                "branch": branch_name,
                "message": f"Branche Git '{branch_name}' créée et validée avec le message : '{commit_message}'"
            }
        except Exception as e:
            return {"success": False, "error": str(e)}

# Global singleton
auto_patcher = AutoPatcher()
